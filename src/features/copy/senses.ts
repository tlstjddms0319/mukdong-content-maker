// 짧은 글이 제목을 되풀이하는지: 글자 조각이 절반 이상 겹치거나, 짧은 글에 제목에 없는 내용 낱말이 하나도 없을 때
// ("지방이 많이 들어 있어요" ← 제목 "지방이 국물에 녹아요": 새 낱말이 "많이·들어·있어"뿐이라 되풀이).
const FUNCTION_WORDS=new Set(["많이","들어","있어","있","없어","없","해요","돼요","나요","해","돼","더","가장","바로","이렇게","그래서","그래","때문","것","수","게","거","정말","아주","조금","살짝","함께","같이","먼저","다시","계속","잘","안","못","이","그","저","때","동안","뒤","앞","속","위","안에","모두","전체","전체에"]);
const contentWords=(text:string)=>text.replace(/[?!.,~·'"“”‘’()\[\]-]/g," ").split(/\s+/)
  .map(word=>word.replace(/(이에요|예요|해요|돼요|서예요|어요|아요|에서|으로|부터|까지|처럼|은|는|이|가|을|를|에|로|과|와|도|만|의|요)$/,""))
  .filter(word=>word.length>=2&&!FUNCTION_WORDS.has(word));
export function restatesHeadline(headline:string,point:string):boolean {
  // 글자 조각 기준은 아주 높을 때만(0.5면 "코끝을 먼저 자극해요" 같은 공통 서술부만으로 걸린다).
  if(topicSimilarity(headline,point)>=0.75)return true;
  const base=contentWords(headline),own=contentWords(point);
  // 제목 낱말의 앞 두 글자가 같으면 같은 말로 본다("녹아요"·"녹아", "국물에"·"국물").
  // 어미를 떼면 한 글자만 남는 말("녹아요"→"녹")은 낱말 목록에서 빠지므로 제목 원문에서도 찾는다.
  const plain=headline.replace(/\s+/g,"");
  const known=(word:string)=>base.some(other=>other.slice(0,2)===word.slice(0,2))||plain.includes(word.slice(0,2));
  return own.length>0&&own.every(known);
}
